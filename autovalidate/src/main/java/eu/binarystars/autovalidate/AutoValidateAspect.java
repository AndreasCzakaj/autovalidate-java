package eu.binarystars.autovalidate;


import org.aspectj.lang.JoinPoint;
import org.aspectj.lang.annotation.*;

import jakarta.validation.*;
import java.util.Set;


/**
 * The AspectJ aspect behind {@link AutoValidate}: it validates objects right after their construction.
 * <p>
 * It is registered in {@code META-INF/aop.xml} and applied by the AspectJ load-time weaver.
 * There's no need to use this class directly.
 */
@Aspect
public class AutoValidateAspect {
    private final ValidatorFactory validatorFactory = Validation.buildDefaultValidatorFactory();
    private final Validator validator = validatorFactory.getValidator();

    /**
     * Creates the aspect, using the default Jakarta Validation provider. Called by AspectJ.
     */
    public AutoValidateAspect() {
    }

    /**
     * Validates a new object of a class that is annotated with {@link AutoValidate}.
     * The builder classes generated by Lombok are skipped.
     *
     * @param joinPoint the execution of the constructor
     * @param <T> the type of the new object
     * @throws ConstraintViolationException if the new object is invalid
     * @throws Throwable if the validation itself fails
     */
    @AfterReturning("execution(*.new(..)) && within(@AutoValidate *) && !within(*.*Builder)")
    public <T> void afterClassAnnotation(JoinPoint joinPoint) throws Throwable {
        validate(joinPoint);
    }

    /**
     * Validates a new object that was created by a constructor annotated with {@link AutoValidate}.
     *
     * @param joinPoint the execution of the constructor
     * @param <T> the type of the new object
     * @throws ConstraintViolationException if the new object is invalid
     * @throws Throwable if the validation itself fails
     */
    @AfterReturning("execution(*.new(..)) && @annotation(AutoValidate)")
    public <T> void afterConstructorAnnotation(JoinPoint joinPoint) throws Throwable {
        validate(joinPoint);
    }

    private <T> void validate(JoinPoint joinPoint) throws Throwable {
        final T object = (T) joinPoint.getThis();
        final Set<ConstraintViolation<T>> violations = validator.validate(object);

        if (violations.size() > 0) {
            throw new ConstraintViolationException(violations);
        }
    }
}
